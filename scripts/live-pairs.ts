/**
 * Live tier: paired fixtures through a real in-process daemon on free models only.
 *
 *   pnpm exec tsx scripts/live-pairs.ts [--pairs 20] [--arm base] [--only-side correct|defect] [--benchmark] [--experiment id]
 *
 * Runs in its own home (~/.polish-experiments), never the owner's: its polish.toml is derived from
 * ~/.polish/polish.toml with routing forced to free_only, every supervisor on a `:free` route, a
 * one-cent USD budget and no attempt token cap (owner decision E). Credentials are read through a
 * symlink to ~/.polish/secrets.env and never copied. Resumable: a (pair, side, arm) already recorded
 * is skipped.
 */
import { existsSync, mkdirSync, readFileSync, symlinkSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { parse, stringify } from "smol-toml";
import { DaemonService } from "../src/daemon/service.js";
import type { Run } from "../src/domain/run.js";
import { generatePairs } from "../src/experiments/pairs.js";
import { runPairSide, type TrialDriver } from "../src/experiments/runner.js";
import { projectExperiment, renderExperiment, trialsFrom } from "../src/observe/experiments.js";

const TERMINAL = new Set(["DONE", "NEEDS_HUMAN", "FAILED"]);
const RUN_WALL_CLOCK_MS = 50 * 60_000;
const MAX_RESUMES = 6;

function flag(name: string): string | undefined {
  const index = process.argv.indexOf(`--${name}`);
  return index === -1 ? undefined : process.argv[index + 1];
}

const home = join(homedir(), ".polish-experiments");
const pairsLimit = Number(flag("pairs") ?? "20");
const arm = flag("arm") ?? "base";
const onlySide = flag("only-side");
const experimentId = flag("experiment") ?? "r13-live";

/**
 * Council models from OpenRouter's live catalogue: free (both prices 0), JSON-capable, one per
 * family, the largest context first. Free routes come and go (minimax-m3:free became paid on the
 * day of the first live smoke), so a list pinned in a config file goes stale.
 */
async function freeCouncilModels(): Promise<string[]> {
  const response = await fetch("https://openrouter.ai/api/v1/models");
  const rows = ((await response.json()) as { data: { id: string; context_length?: number; pricing?: { prompt?: unknown; completion?: unknown }; supported_parameters?: string[] }[] }).data;
  const families = new Set<string>();
  return rows
    .filter((row) => row.id.endsWith(":free") && String(row.pricing?.prompt) === "0" && String(row.pricing?.completion) === "0")
    .filter((row) => (row.supported_parameters ?? []).some((parameter) => parameter === "response_format" || parameter === "structured_outputs"))
    .filter((row) => (row.context_length ?? 0) >= 128_000)
    .sort((a, b) => (b.context_length ?? 0) - (a.context_length ?? 0) || a.id.localeCompare(b.id))
    .filter((row) => {
      const family = row.id.split("/")[0] ?? row.id;
      if (families.has(family)) return false;
      families.add(family);
      return true;
    })
    .slice(0, 4)
    .map((row) => `openrouter:${row.id}`);
}

async function prepareHome(): Promise<void> {
  mkdirSync(home, { recursive: true });
  const owner = parse(readFileSync(join(homedir(), ".polish", "polish.toml"), "utf8")) as Record<string, unknown>;
  const providers = (owner["providers"] as Record<string, unknown>[] | undefined ?? []).filter((provider) => provider["kind"] === "openrouter");
  const freeModels = await freeCouncilModels();
  if (freeModels.length < 2) throw new Error(`too few free JSON council models on OpenRouter: ${freeModels.join(", ")}`);
  console.log(`council models: ${freeModels.join(", ")}`);
  const supervisors = ((owner["supervisors"] as Record<string, unknown>[] | undefined) ?? []).map((supervisor, index) => ({
    ...supervisor,
    // Each role leads with a different model, so one rate-limited route does not stall all three.
    models: [...freeModels.slice(index % freeModels.length), ...freeModels.slice(0, index % freeModels.length)],
  }));
  const config = {
    ...owner,
    providers,
    supervisors,
    routing: { ...(owner["routing"] as Record<string, unknown> | undefined), costEligibility: "free_only" },
    // A cent, not zero: zero reads as already spent. Free routes cost $0, so only a paid call reaches it.
    budget: { maxRunUsd: 0.01, maxRunWallClockMinutes: 50 },
  };
  delete (config.routing as Record<string, unknown>)["maxInputCostPerM"];
  delete (config.routing as Record<string, unknown>)["maxOutputCostPerM"];
  if (process.argv.includes("--advisor")) config["agent"] = { ...(owner["agent"] as Record<string, unknown> | undefined), advisor: true };
  writeFileSync(join(home, "polish.toml"), `# Generated by scripts/live-pairs.ts from ~/.polish/polish.toml: free_only, one cent.\n${stringify(config)}\n`);
  const secrets = join(home, "secrets.env");
  if (!existsSync(secrets)) symlinkSync(join(homedir(), ".polish", "secrets.env"), secrets);
}

async function main(): Promise<void> {
  await prepareHome();
  const service = new DaemonService({ home });
  service.start();
  try {
    if (process.argv.includes("--benchmark")) {
      const result = await service.handle("benchmark.review", { seed: 42, configuration: "operational" }) as { summary: string };
      console.log(result.summary);
    }
    const { pairs } = generatePairs(join(home, "pairs"), { limit: pairsLimit });
    const recorded = () => trialsFrom(service.store.repos.runs.listAll().flatMap((run) => service.store.events.list(run.id, { types: ["experiment.trial_recorded"] })));
    const driver: TrialDriver = {
      store: service.store,
      startRun: async (project, mission) => ((await service.handle("run", { project, mission, runtime: "auto" })) as { id: string }).id,
      waitForTerminal: async (runId) => {
        const deadline = Date.now() + RUN_WALL_CLOCK_MS;
        let resumes = 0;
        for (;;) {
          const run = service.store.repos.runs.get(runId);
          if (run !== null && TERMINAL.has(run.phase)) return run;
          // A driver failure pauses a run for an operator. Free routes are paused mostly by the
          // shared per-minute allowance, which lifts on its own, so wait and resume a few times.
          if (run?.control === "PAUSED" && resumes < MAX_RESUMES && Date.now() < deadline) {
            resumes += 1;
            await new Promise((resolve) => setTimeout(resolve, 90_000));
            await service.handle("resume", { runId });
            continue;
          }
          if (run?.control === "PAUSED" || Date.now() > deadline) {
            await service.handle("stop", { runId });
            return service.store.repos.runs.get(runId) as Run;
          }
          await new Promise((resolve) => setTimeout(resolve, 5_000));
        }
      },
    };
    for (const pair of pairs) {
      for (const side of ["correct", "defect"] as const) {
        if (onlySide !== undefined && side !== onlySide) continue;
        const done = recorded().some((trial) => trial.experimentId === experimentId && trial.arm === arm && trial.pairId === pair.id && trial.side === side);
        if (done) continue;
        const started = Date.now();
        const trial = await runPairSide(driver, pair, side, { experimentId, arm, workDir: join(home, "work", experimentId, arm) });
        console.log(JSON.stringify({ ...trial, minutes: Math.round((Date.now() - started) / 6_000) / 10 }));
      }
    }
    console.log(renderExperiment(projectExperiment(experimentId, recorded())));
  } finally {
    await service.close();
  }
}

main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
